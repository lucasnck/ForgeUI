bool validInteractionProperties(String slug, Map properties) {
  final schema = interactionContracts[slug];
  if (schema == null) return false;
  for (final e in properties.entries) {
    if (e.key == 'theme' || e.key == 'scenario') continue;
    final f = schema[e.key], v = e.value;
    if (f == null) return false;
    switch (f['kind']) {
      case 'boolean':
        if (v is! bool) return false;
      case 'text':
        if (v is! String ||
            v.length > 200 ||
            (f['nonblank'] == true && v.trim().isEmpty)) return false;
      case 'select':
        if (!(f['options'] as List).contains(v)) return false;
      case 'number':
        if (v is! int || v < (f['min'] as int) || v > (f['max'] as int))
          return false;
    }
  }
  if (interactionFamilies[slug] == 'accordion' &&
      properties['expanded'] == 'both' &&
      (properties['multiple'] ?? false) != true) return false;
  return true;
}
