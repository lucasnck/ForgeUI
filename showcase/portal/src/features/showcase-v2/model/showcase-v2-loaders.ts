validateShowcaseV2Index(showcaseV2Index, Object.keys(loaders));

export async function loadShowcaseV2Definition(slug: string) {
  const entry = showcaseV2Index.find((item) => item.slug === slug);
  if (!entry || !Object.hasOwn(loaders, slug)) throw new Error("Unknown Showcase V2 entry");
  const { default: definition } = await loaders[slug]();
  validateShowcaseV2Definition(definition, entry);
  return definition;
}
