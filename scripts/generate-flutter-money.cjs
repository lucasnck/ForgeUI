// Derive native decimal metadata from the same ECMA-402 locale source as Web.
// No monetary amount is converted to binary floating point by the Dart helper.
const fs=require('fs');
const codes=[...Intl.supportedValuesOf('currency'),'ZZZ'];
const output={};
function affix(parts){
 const first=parts.findIndex(p=>p.type==='integer');
 let last=parts.length-1;while(last>first&&!['integer','group','decimal','fraction'].includes(parts[last].type))last--;
 return [parts.slice(0,first).map(p=>p.value).join(''),parts.slice(last+1).map(p=>p.value).join('')];
}
for(const locale of ['pt-BR','es','en']){
 const parts=new Intl.NumberFormat(locale).formatToParts(-1234567.89);
 output[locale]={decimal:parts.find(p=>p.type==='decimal').value,group:parts.find(p=>p.type==='group').value,
 minus:parts.find(p=>p.type==='minusSign').value,groupMin:new Intl.NumberFormat(locale,{useGrouping:true}).formatToParts(1000).some(p=>p.type==='group')?4:5,currencies:{}};
 for(const currency of codes){
 const format=new Intl.NumberFormat(locale,{style:'currency',currency});
 const patterns={};
 for(const display of ['code','symbol','narrowSymbol','name']){
 const f=new Intl.NumberFormat(locale,{style:'currency',currency,currencyDisplay:display});
 patterns[display]=[1,2,-1,-2].map(n=>affix(f.formatToParts(n)));
 }
 output[locale].currencies[currency]={digits:format.resolvedOptions().maximumFractionDigits,patterns};
 }
}
const path='app/library/lib/src/generated/forge_money_data.g.dart';
fs.writeFileSync(path,"// Generated by scripts/generate-flutter-money.cjs. ECMA-402 locale metadata.\nconst String forgeMoneyDataJson = r'''"+JSON.stringify(output)+"''';\n");
console.log('Generated currency metadata for '+codes.length+' currencies in 3 locales.');
